"""Compile checked-in RC sources. RES files are build products, never source inputs."""
from pathlib import Path
import argparse,os,shutil,subprocess,xml.etree.ElementTree as E
ROOT=Path(__file__).resolve().parents[1]
def compiler():
    configured=os.environ.get('RC_EXE')
    if configured:
        path=Path(configured)
        if not path.is_file():raise SystemExit('RC_EXE does not exist')
        return path
    kits=Path(os.environ.get('ProgramFiles(x86)',os.environ.get('ProgramFiles','')))/'Windows Kits/10/bin'
    choices=sorted(kits.glob('*/x64/rc.exe'),reverse=True)
    if choices:return choices[0]
    path=shutil.which('rc.exe')
    if path:return Path(path)
    raise SystemExit('Windows SDK Resource Compiler missing; install it or set RC_EXE.')
def metadata(version=None,stub=False):
    ns={'m':'http://schemas.microsoft.com/developer/msbuild/2003'}
    project=E.parse(ROOT/'src/MSFS2024-FDR.dproj')
    base=next(g for g in project.findall('m:PropertyGroup',ns) if g.get('Condition')=="'$(Base)'!=''")
    numbers=[int(base.findtext('m:VerInfo_'+x,'0',ns)) for x in ['MajorVer','MinorVer','Release','Build']]
    if version:numbers=list(map(int,version.split('.')))
    assert len(numbers)==4 and all(0<=x<=65535 for x in numbers)
    values=dict(part.split('=',1) for part in base.findtext('m:VerInfo_Keys','',ns).split(';') if '=' in part)
    values['FileVersion']='.'.join(map(str,numbers))
    if stub:values.update(FileDescription='MSFS24-FDR Setup placeholder',OriginalFilename='MSFS24-FDR-Setup.exe',InternalName='MSFS24-FDR-Setup',ProductName='MSFS24-FDR')
    return numbers,values
def compile_rc(source,destination,work=None):
    args=[str(compiler()),'/nologo','/c65001']
    if work:args+=['/I',str(work)]
    args+=['/fo',str(destination.resolve()),source.name]
    destination.parent.mkdir(parents=True,exist_ok=True)
    subprocess.run(args,cwd=source.parent,check=True)
    if destination.stat().st_size<=32:raise RuntimeError('Empty resource output: '+str(destination))
def setup_header():
    # Compatibility for the separately maintained installer only.
    numbers,values=metadata(stub=True)
    work=ROOT/'.build/Resources/setup';work.mkdir(parents=True,exist_ok=True)
    def literal(value):return '"'+value.replace('\\','\\\\').replace('"','\\"')+'\\0"'
    header='#define APP_FILE_VERSION '+','.join(map(str,numbers))+'\n'
    header+=''.join('#define APP_'+key.upper()+' '+literal(value)+'\n' for key,value in values.items())
    (work/'Version.rh').write_text(header,encoding='utf-8-sig')
    return work
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--app',action='store_true');p.add_argument('--stub',action='store_true');p.add_argument('--vendor',action='store_true');p.add_argument('--setup',action='store_true');p.add_argument('--version');p.add_argument('--output',type=Path);a=p.parse_args()
    if a.app:pass # Project RES is generated by Delphi MSBuild from DPROJ.
    if a.stub:raise SystemExit("Build the stub DPROJ with MSBuild.")
    if a.setup:
        work=setup_header()
        setup=ROOT.parent/'MSFS2024-FDR-Setup/src'
        compile_rc(setup/'MSFS24-FDR-Setup.rc',setup/'MSFS24-FDR-Setup.res',work)
        compile_rc(setup/'SetupI18n.rc',setup/'SetupI18n.res')
    if a.vendor:
        for name in ['i18n','i18nDB','i18nDesign','i18nFlags_16x11']:
            source=ROOT/'vendor/i18n/Packages'/(name+'.rc');compile_rc(source,source.with_suffix('.res'))
    print('PASS: resources rebuilt from checked-in RC sources.')
